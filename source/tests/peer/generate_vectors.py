#!/usr/bin/env python3
"""Independent endpoint/PeerId vectors using Python's standard library."""
from pathlib import Path
import argparse
import base64
import hashlib
import ipaddress
import struct
cases=[('ipv4',1,ipaddress.ip_address('203.0.113.7').packed,8226),
       ('ipv6',2,ipaddress.ip_address('2001:db8::1').packed,8226),
       ('tor',4,bytes(range(32)),8226),('i2p',5,bytes(range(32)),8226),
       ('other_port',1,ipaddress.ip_address('203.0.113.7').packed,8227)]
text='// Independent fixtures generated by generate_vectors.py.\n#pragma once\n#include <string_view>\nnamespace peer_vectors {\n'
for name,network,address,port in cases:
    canonical=b'\x01'+bytes.fromhex('a2b2e2f2')+bytes([network,len(address)])+address+struct.pack('>H',port)
    peerid=hashlib.sha256(b'BSTY-FastSeed/PeerId/v1\0'+canonical).hexdigest()
    text+=f'inline constexpr std::string_view {name}_bytes="{canonical.hex()}";\n'
    text+=f'inline constexpr std::string_view {name}_id="{peerid}";\n'
key=bytes(range(32))
onion=base64.b32encode(key+hashlib.sha3_256(b'.onion checksum'+key+b'\x03').digest()[:2]+b'\x03').decode().lower()+'.onion'
i2p=base64.b32encode(key).decode().rstrip('=').lower()+'.b32.i2p'
text+=f'inline constexpr std::string_view tor_host="{onion}";\ninline constexpr std::string_view i2p_host="{i2p}";\n}}\n'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
path=Path(__file__).with_name('known_peer_vectors.hpp')
if args.check:
    if path.read_text()!=text:raise SystemExit('Peer identity fixture mismatch')
else:path.write_text(text,encoding='utf-8',newline='\n')
print('PASS: five independent endpoint/PeerId vectors and two overlay hostnames')
